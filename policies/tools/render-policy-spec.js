#!/usr/bin/env node
'use strict';

/**
 * Render docs/policies/governance-policy-specification.md from the canonical
 * bundle so the human-readable specification cannot drift from the JSON.
 *
 * Usage (repository root): node policies/tools/render-policy-spec.js [--check]
 */

const fs = require('fs');
const path = require('path');
const { clauseRef, loadBundle } = require('../lib/bundle');

const ROOT = path.resolve(__dirname, '..', '..');
const OUTPUT = path.join(ROOT, 'docs', 'policies', 'governance-policy-specification.md');

const bullets = (items, indent = '  ') => (items.length > 0
  ? items.map((item) => `${indent}- ${item}`).join('\n')
  : `${indent}- none`);

function renderClause(bundle, clause) {
  const ref = clauseRef(clause, bundle.version);
  return [
    `### ${ref} — ${clause.title}`,
    '',
    `- **Policy ID:** ${clause.policyId}`,
    `- **Clause ID:** ${clause.clauseId}`,
    `- **Version:** ${bundle.version}`,
    `- **Effect:** ${clause.effect}${clause.reasonCode ? ` (reason code \`${clause.reasonCode}\`)` : ''}`,
    `- **Precedence:** ${clause.precedence === null ? 'informational, not ordered' : clause.precedence}`,
    `- **Description:** ${clause.text}`,
    `- **Organization scope:** ${clause.scope.organizations}`,
    `- **Role scope:** ${clause.scope.roles}`,
    `- **Resource scope:** ${clause.scope.recordTypes}`,
    `- **Operation scope:** ${clause.scope.actions}`,
    '- **Conditions:**',
    bullets(clause.conditions),
    '- **Exceptions:**',
    bullets(clause.exceptions),
    `- **Effective state:** ${clause.effectiveState}`,
    `- **Source:** ${clause.source}`,
    `- **Classification:** ${clause.classification}`,
    ...(clause.notes.length > 0 ? ['- **Notes:**', bullets(clause.notes)] : []),
    '',
  ].join('\n');
}

function renderRbac(bundle) {
  return Object.entries(bundle.rbac).map(([role, permissions]) => {
    const organization = bundle.roles[role]?.organization || 'undefined';
    const actions = bundle.vocabularies.actions
      .map((action) => `${action}: ${(permissions[action] || []).join(', ') || 'none'}`)
      .join('; ');
    return `- **${role}** (${organization}) — ${actions}`;
  }).join('\n');
}

function render() {
  const { bundle, bundleHash } = loadBundle();
  return [
    '# DIAS governance policy specification',
    '',
    '<!-- Generated by policies/tools/render-policy-spec.js. Do not edit by hand. -->',
    '',
    `- **Bundle:** \`${bundle.bundleId}\` version \`${bundle.version}\``,
    `- **Schema:** \`${bundle.schemaVersion}\``,
    `- **Status:** \`${bundle.status}\``,
    `- **Effective from:** ${bundle.effectiveFrom}`,
    `- **Canonical SHA-256:** \`${bundleHash}\``,
    `- **Source file:** \`policies/dias-governance-policy-v1.json\``,
    `- **Provenance:** ${bundle.provenance.type}. Derived from ${bundle.provenance.derivedFrom}.`,
    '- **Changes from the source policy:**',
    bullets(bundle.provenance.changesFromSource),
    `- **Open questions:** \`${bundle.provenance.openQuestions}\``,
    '',
    '## How the policy is used',
    '',
    '- The recommendation assistant receives these clauses as policy context and recommends ALLOW or DENY.',
    '- The auditor makes the final decision on every request without an active dynamic authorization.',
    '- `policies/reference-oracle/` applies the same clauses offline to label synthetic data. The live workflow never calls it.',
    '',
    '## Precedence',
    '',
    `- **Method:** ${bundle.precedence.method}`,
    `- **DENY order:** ${bundle.precedence.denyOrder.join(' → ')}`,
    `- **Default:** ${bundle.precedence.defaultClause}`,
    `- **Policy references on ALLOW:** ${bundle.precedence.allowPolicyRefs.join(', ')}`,
    `- **Policy references on DENY:** ${bundle.precedence.policyRefsOnDeny}`,
    '',
    '## Clauses',
    '',
    ...bundle.clauses.map((clause) => renderClause(bundle, clause)),
    '## Vocabularies',
    '',
    `- **Actions:** ${bundle.vocabularies.actions.join(', ')}`,
    `- **Purposes:** ${bundle.vocabularies.purposes.join(', ')}`,
    `- **Record types:** ${bundle.vocabularies.recordTypes.join(', ')}`,
    `- **Sensitivity levels:** ${bundle.vocabularies.sensitivityLevels.join(', ')}`,
    `- **Clearance order:** ${bundle.vocabularies.clearanceOrder.join(' < ')}`,
    `- **Unknown sensitivity treated as:** ${bundle.vocabularies.unknownSensitivityTreatedAs}`,
    `- **Organizations by MSP:** ${Object.entries(bundle.vocabularies.organizationsByMsp).map(([msp, org]) => `${msp} → ${org}`).join(', ')}`,
    '',
    '## Role lists',
    '',
    `- **Assignment-exempt:** ${bundle.roleLists.assignmentExempt.join(', ')}`,
    `- **Juvenile-authorized:** ${bundle.roleLists.juvenileAuthorized.join(', ')}`,
    `- **Victim-data blocked:** ${bundle.roleLists.victimDataBlocked.join(', ')}`,
    '',
    '## RBAC matrix',
    '',
    renderRbac(bundle),
    '',
    '## Review flags',
    '',
    ...Object.entries(bundle.reviewFlags).map(([flag, meaning]) => `- **${flag}:** ${meaning}`),
    '',
    '## Missing evidence',
    '',
    `- ${bundle.missingEvidence.instruction}`,
    '',
  ].join('\n');
}

function main() {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== text) {
      console.error('policy specification is out of date; run policies/tools/render-policy-spec.js');
      process.exitCode = 1;
      return;
    }
    console.log('policy specification is up to date');
    return;
  }
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, text);
  console.log(`wrote ${path.relative(ROOT, OUTPUT)}`);
}

if (require.main === module) main();

module.exports = { render };
