#!/usr/bin/env node
'use strict';

/**
 * Build the model comparison tables from evaluation runs that already exist.
 *
 * It reads `metrics.json` from each run directory and emits CSV and LaTeX. It
 * never runs inference, so a table can be rebuilt after a metric definition
 * changes without spending hours of GPU time, and two models are only ever
 * compared on sets both actually ran.
 *
 *   node experiments/dias-finetuning/v2/eval/compare.js \
 *     --runs untuned=experiments/runs/.../baseline,v7=experiments/runs/.../v7 \
 *     --out results/tables
 */

const fs = require('fs');
const path = require('path');

const HEADLINE = Object.freeze([
  ['examples', (m) => m.examples],
  ['schema_valid_rate', (m) => m.schemaValidRate],
  ['decision_accuracy', (m) => m.decisionAccuracy],
  ['balanced_accuracy', (m) => m.balancedAccuracy],
  ['macro_f1', (m) => m.macroF1],
  ['allow_precision', (m) => m.allow.precision],
  ['allow_recall', (m) => m.allow.recall],
  ['deny_precision', (m) => m.deny.precision],
  ['deny_recall', (m) => m.deny.recall],
  ['false_allow_count', (m) => m.falseAllow.count],
  ['false_allow_rate', (m) => m.falseAllow.ofDenyExamples],
  ['false_deny_count', (m) => m.falseDeny.count],
  ['false_deny_rate', (m) => m.falseDeny.ofAllowExamples],
  ['reason_code_accuracy', (m) => m.reasonCodeAccuracy],
  ['policy_ref_accuracy', (m) => m.policyRefAccuracy],
  ['decision_and_reason_accuracy', (m) => m.decisionAndReasonAccuracy],
  ['fully_correct_rate', (m) => m.fullyCorrectRate],
  ['latency_median_ms', (m) => m.latencyMs.median],
  ['latency_p95_ms', (m) => m.latencyMs.p95],
  ['latency_p99_ms', (m) => m.latencyMs.p99],
]);

const show = (value) => (value === null || value === undefined ? '' : String(value));

function parseRuns(spec) {
  return spec.split(',').map((entry) => {
    const [label, dir] = entry.split('=');
    if (!label || !dir) throw new Error(`--runs entries look like label=path, got '${entry}'`);
    const file = path.resolve(dir, 'metrics.json');
    if (!fs.existsSync(file)) throw new Error(`no metrics.json in ${dir}`);
    return { label, dir, report: JSON.parse(fs.readFileSync(file, 'utf8')) };
  });
}

/** Sets every run evaluated. Comparing on a set only one ran would be dishonest. */
function commonSets(runs) {
  const [first, ...rest] = runs.map((run) => new Set(Object.keys(run.report.sets)));
  return [...first].filter((name) => rest.every((set) => set.has(name))).sort();
}

function csvTable(runs, sets) {
  const rows = [['set', 'metric', ...runs.map((r) => r.label)]];
  for (const set of sets) {
    for (const [metric, read] of HEADLINE) {
      rows.push([set, metric, ...runs.map((run) => show(read(run.report.sets[set])))]);
    }
  }
  return rows.map((row) => row.join(',')).join('\n');
}

/** The headline table a paper would print: one row per set, per model. */
function summaryTable(runs, sets) {
  const rows = [[
    'set', 'model', 'examples', 'schema_valid_rate', 'decision_accuracy',
    'balanced_accuracy', 'macro_f1', 'false_allow_count', 'false_allow_rate',
    'false_deny_count', 'reason_code_accuracy', 'latency_p95_ms',
  ]];
  for (const set of sets) {
    for (const run of runs) {
      const m = run.report.sets[set];
      rows.push([
        set, run.label, m.examples, show(m.schemaValidRate), show(m.decisionAccuracy),
        show(m.balancedAccuracy), show(m.macroF1), m.falseAllow.count,
        show(m.falseAllow.ofDenyExamples), m.falseDeny.count,
        show(m.reasonCodeAccuracy), show(m.latencyMs.p95),
      ]);
    }
  }
  return rows.map((row) => row.join(',')).join('\n');
}

function latexTable(runs, sets) {
  const escape = (text) => String(text).replace(/_/g, '\\_');
  const lines = [
    '% Generated by experiments/dias-finetuning/v2/eval/compare.js — do not edit by hand.',
    '\\begin{tabular}{llrrrrr}',
    '\\toprule',
    'Set & Model & Acc. & Bal. acc. & Macro-F1 & False ALLOW & Valid JSON \\\\',
    '\\midrule',
  ];
  for (const set of sets) {
    for (const run of runs) {
      const m = run.report.sets[set];
      lines.push([
        escape(set), escape(run.label),
        show(m.decisionAccuracy), show(m.balancedAccuracy), show(m.macroF1),
        `${m.falseAllow.count} (${show(m.falseAllow.ofDenyExamples)})`,
        show(m.schemaValidRate),
      ].join(' & ') + ' \\\\');
    }
    lines.push('\\midrule');
  }
  lines[lines.length - 1] = '\\bottomrule';
  lines.push('\\end{tabular}');
  return lines.join('\n');
}

/** Per-model confusion matrices, so a headline number can be checked against counts. */
function confusionTable(runs, sets) {
  const rows = [['set', 'model', 'true_allow_pred_allow', 'true_allow_pred_deny',
    'true_deny_pred_allow', 'true_deny_pred_deny', 'invalid']];
  for (const set of sets) {
    for (const run of runs) {
      const m = run.report.sets[set];
      const c = m.confusionMatrix;
      rows.push([set, run.label, c.ALLOW.ALLOW, c.ALLOW.DENY, c.DENY.ALLOW, c.DENY.DENY, m.invalid]);
    }
  }
  return rows.map((row) => row.join(',')).join('\n');
}

function main() {
  const args = {};
  for (let i = 0; i < process.argv.length; i += 1) {
    if (process.argv[i].startsWith('--')) args[process.argv[i].slice(2)] = process.argv[i + 1];
  }
  if (!args.runs) throw new Error('--runs label=dir[,label=dir...] is required');
  const runs = parseRuns(args.runs);
  const sets = commonSets(runs);
  if (sets.length === 0) throw new Error('the runs share no evaluated set');
  const outDir = path.resolve(args.out || 'results/tables');
  fs.mkdirSync(outDir, { recursive: true });

  const prefix = args.prefix || 'dias_model_comparison';
  fs.writeFileSync(path.join(outDir, `${prefix}_full.csv`), `${csvTable(runs, sets)}\n`);
  fs.writeFileSync(path.join(outDir, `${prefix}.csv`), `${summaryTable(runs, sets)}\n`);
  fs.writeFileSync(path.join(outDir, `${prefix}_confusion.csv`), `${confusionTable(runs, sets)}\n`);
  fs.writeFileSync(path.join(outDir, `${prefix}.tex`), `${latexTable(runs, sets)}\n`);

  console.log(`models:  ${runs.map((r) => r.label).join(', ')}`);
  console.log(`sets:    ${sets.join(', ')}`);
  for (const set of sets) {
    console.log(`\n${set}`);
    for (const run of runs) {
      const m = run.report.sets[set];
      console.log(`  ${run.label.padEnd(26)} acc ${show(m.decisionAccuracy).padEnd(9)}`
        + ` macroF1 ${show(m.macroF1).padEnd(9)} falseALLOW ${String(m.falseAllow.count).padStart(4)}`
        + ` falseDENY ${String(m.falseDeny.count).padStart(4)} valid ${show(m.schemaValidRate)}`);
    }
  }
  console.log(`\nwritten to ${outDir}`);
}

if (require.main === module) main();
module.exports = { HEADLINE, commonSets, csvTable, latexTable, summaryTable };
